"""Typed contracts for candidate batching, identity evidence, and node resolution."""

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field, model_validator

from product.application.references import (
    OwnerContextDTO,
    ReferenceEntryDTO,
)
from product.application.states.ingestion.node_candidate import NodeCandidate
from product.graph import IdentityMatchKind, NodeType


class NodeBatchPolicyDTO(BaseModel):
    """Launch-configured deterministic candidate batching policy."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    maximum_batch_size: int = Field(
        default=15,
        ge=1,
        description="Maximum candidates passed to one node-resolution state invocation.",
    )
    dedicated_type_minimum: int = Field(
        default=5,
        ge=1,
        description="Minimum same-type remainder receiving a dedicated invocation.",
    )

    @model_validator(mode="after")
    def _validate_threshold(self) -> "NodeBatchPolicyDTO":
        if self.dedicated_type_minimum > self.maximum_batch_size:
            raise ValueError(
                "dedicated_type_minimum cannot exceed maximum_batch_size."
            )
        return self


class ReferencedNodeCandidateDTO(BaseModel):
    """One generated candidate paired with its backend-issued workflow reference."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    candidate_ref: str = Field(description="Exact active reference for this candidate.")
    candidate: NodeCandidate = Field(description="Typed candidate generated by the prior state.")


class NodeCandidateBatchDTO(BaseModel):
    """One bounded candidate group passed to the same resolution state class."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    batch_id: str = Field(description="Deterministic workflow-local batch identifier.")
    node_types: list[NodeType] = Field(
        description="Distinct node types present in this batch in first-seen order."
    )
    candidates: list[ReferencedNodeCandidateDTO] = Field(
        min_length=1,
        description="Candidates resolved together in this invocation.",
    )


class IdentityMatchEvidenceDTO(BaseModel):
    """One model-safe existing-node match supplied as evidence only."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    existing_ref: str = Field(description="Existing node reference supplied in active context.")
    match_kind: IdentityMatchKind = Field(description="Deterministic match classification.")
    display_name: str = Field(description="Readable title of the possible existing identity.")
    aliases: list[str] = Field(description="Known aliases of the possible existing identity.")


class CandidateIdentityEvidenceDTO(BaseModel):
    """Bounded identity evidence associated with exactly one candidate reference."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    candidate_ref: str = Field(description="Candidate reference this evidence concerns.")
    matches: list[IdentityMatchEvidenceDTO] = Field(
        description="Possible existing identities; an empty list means no match was found."
    )


class NodeResolutionStateInputDTO(BaseModel):
    """Current batch, evidence, owner, and model-safe references for node resolution."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    batch: NodeCandidateBatchDTO
    identity_evidence: list[CandidateIdentityEvidenceDTO]
    owner: OwnerContextDTO
    references: list[ReferenceEntryDTO]


class NodeResolutionOutcome(StrEnum):
    """Semantic result for one candidate after the state and its tools complete."""

    CREATED = "created"
    SELECTED_EXISTING = "selected_existing"
    UPDATED_EXISTING = "updated_existing"
    DEFERRED = "deferred"


class NodeResolutionOutcomeDTO(BaseModel):
    """One model-facing resolution outcome with no backend identifier."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    candidate_ref: str = Field(description="Exact candidate reference being resolved.")
    outcome: NodeResolutionOutcome = Field(description="Resolution applied to this candidate.")
    node_ref: str | None = Field(
        description="Created or selected node reference, or null only when deferred."
    )
    summary: str = Field(description="Concise explanation of the completed resolution.")
    changes: list[str] = Field(
        description="Readable fields added or changed; empty when no node update occurred."
    )


class NodeResolutionStateResultDTO(BaseModel):
    """Complete model-facing result for one node-resolution batch."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    outcomes: list[NodeResolutionOutcomeDTO] = Field(
        description="Exactly one terminal resolution outcome per input candidate."
    )

    @model_validator(mode="after")
    def _validate_unique_candidates(self) -> "NodeResolutionStateResultDTO":
        refs = [outcome.candidate_ref for outcome in self.outcomes]
        if len(refs) != len(set(refs)):
            raise ValueError("Resolution outcomes cannot repeat a candidate reference.")
        return self


